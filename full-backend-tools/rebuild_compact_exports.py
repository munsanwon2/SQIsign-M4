#!/usr/bin/env python3
"""Recreate the three Cortex-M4 exports from the pinned compact-SQIsign tree."""

import argparse
import hashlib
import json
from math import isqrt
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tarfile
import tempfile


TOOLS = Path(__file__).resolve().parent
LEVELS = (1, 3, 5)


def pin():
    for line in (TOOLS.parent / "SOURCE_URLS.lock").read_text(encoding="utf-8").splitlines():
        fields = line.split()
        if fields and fields[0] == "compact-SQIsign":
            return fields[2]
    raise ValueError("compact-SQIsign revision is missing from SOURCE_URLS.lock")


def verify_precomputation(root, level):
    directory = root / f"src/precomp/ref/lvl{level}"
    parameters = json.loads((directory / "parameters.json").read_bytes())
    if parameters["level"] != f"lvl{level}" or parameters["orders"][0] != {
        "connecting_denominator": 2,
        "connecting_norm": "1",
        "order_denominator": 2,
        "q": 1,
    }:
        raise ValueError(f"unexpected O0 parameters for level {level}")
    for name, expected in parameters["generated_sha256"].items():
        generated = (directory / name).resolve()
        if not generated.is_relative_to(root):
            raise ValueError(f"generated path escapes the source tree: {name}")
        digest = hashlib.sha256(generated.read_bytes()).hexdigest()
        if digest != expected:
            raise ValueError(f"upstream generated file hash mismatch: {generated}")
    return parameters


def select_first_entry(source, name, entries):
    marker = f"{name}[{entries}] = {{"
    start = source.index(marker) + len(marker)
    depth = 1
    first_comma = None
    for end in range(start, len(source)):
        token = source[end]
        if token == "{":
            depth += 1
        elif token == "}":
            depth -= 1
        elif token == "," and depth == 1 and first_comma is None:
            first_comma = end
        if depth == 0:
            break
    if depth != 0 or first_comma is None:
        raise ValueError(f"unexpected generated array layout: {name}")
    source = source[:first_comma] + source[end:]
    return source.replace(marker, f"{name}[1] = {{", 1)


def configure_qlapoti(directory, parameters):
    entries = len(parameters["orders"])
    groups = {
        "quaternion_data": (
            ("EXTREMAL_ORDERS", "CONNECTING_IDEALS", "CONJUGATING_ELEMENTS"),
            "NUM_ALTERNATE_EXTREMAL_ORDERS",
        ),
        "endomorphism_action": (("CURVES_WITH_ENDOMORPHISMS",), "NUM_ALTERNATE_STARTING_CURVES"),
    }
    for filename, (symbols, count_macro) in groups.items():
        path = directory / f"{filename}.c"
        source = path.read_text(encoding="utf-8")
        for symbol in symbols:
            source = select_first_entry(source, symbol, entries)
        path.write_text(source, encoding="utf-8", newline="\n")

        path = directory / "include" / f"{filename}.h"
        header = path.read_text(encoding="utf-8")
        for symbol in symbols:
            header = header.replace(f"{symbol}[{entries}]", f"{symbol}[1]")
        header = header.replace(f"#define {count_macro} {entries - 1}", f"#define {count_macro} 0")
        path.write_text(header, encoding="utf-8", newline="\n")

    path = directory / "include/quaternion_constants.h"
    header = re.sub(r"^#define FINDUV_.*\n", "", path.read_text(encoding="utf-8"), flags=re.M)
    used_torsion = parameters["f"] - 2
    header = header.rstrip() + (
        "\n#define QUAT_qlapoti_gen_bound_bits 17\n"
        f"#define QUAT_qlapoti_used_power_of_two {used_torsion}\n"
        "#define QUAT_qlapoti_iteration_bound 20000\n"
    )
    path.write_text(header, encoding="utf-8", newline="\n")


def write_qlapoti_primes(root):
    primes = [2]
    candidate = 5
    while len(primes) < 101:
        if all(candidate % divisor for divisor in range(3, isqrt(candidate) + 1, 2)):
            primes.append(candidate)
        candidate += 4
    path = root / "src/id2iso/ref/lvlx/qlapoti_cornacchia_primes.inc"
    lines = ["/* Generated by rebuild_compact_exports.py for q = 1. */"]
    lines.extend("    " + ", ".join(map(str, primes[i:i + 12])) + ","
                 for i in range(0, len(primes), 12))
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def rebuild(upstream, output):
    if output.exists():
        raise ValueError(f"export destination already exists: {output}")
    with tempfile.TemporaryDirectory(prefix="sqisign-m4-source-") as temporary:
        root = Path(temporary) / "source"
        archive = Path(temporary) / "upstream.tar"
        subprocess.run(
            ["git", "-C", str(upstream), "-c", "core.autocrlf=false", "archive", "--format=tar",
             f"--output={archive}", pin()],
            check=True,
        )
        root.mkdir()
        with tarfile.open(archive) as stream:
            stream.extractall(root, filter="data")
        parameters = {level: verify_precomputation(root, level) for level in LEVELS}
        subprocess.run(
            ["git", "apply", "--whitespace=nowarn", str(TOOLS / "compact-cortex-m4.patch")],
            cwd=root,
            check=True,
        )
        for level, record in parameters.items():
            configure_qlapoti(root / f"src/precomp/ref/lvl{level}", record)
        write_qlapoti_primes(root)
        subprocess.run(
            [sys.executable, str(TOOLS / "curate_pqm4_library.py"), "--source", str(root),
             "--output", str(output), "--levels", *map(str, LEVELS), "--export"],
            check=True,
        )
        for level in LEVELS:
            shutil.copyfile(root / f"src/precomp/ref/lvl{level}/parameters.json",
                            output / f"lvl{level}/parameters.json")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--upstream", type=Path, required=True, help="local compact-SQIsign Git clone")
    parser.add_argument("--output", type=Path, required=True, help="new export directory")
    options = parser.parse_args()
    rebuild(options.upstream.resolve(), options.output.resolve())
